/**
 * Build `client/client.js` for dsh-composer-kit.
 *
 * The five source plugins each ship a browser artifact in the
 * `window.__ModuleLoader__.load({ id, factory })` format. The browser roster
 * only applies the ONE module whose id equals the package name, so five
 * separate modules cannot survive a merge. This script extracts each factory
 * body verbatim, re-wraps it in an IIFE (so every piece keeps its own scope and
 * its own `module`/`exports` shim), and emits one module that applies all five.
 *
 * Nothing inside a piece is rewritten: order values, CSS, locale dictionaries,
 * slot ids and event handlers stay exactly as they were in the source package.
 *
 * Usage: node scripts/build-client.mjs [--check]
 *   --check  regenerate into memory and compare with the file on disk
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, '..')
const target = join(pkgRoot, 'client', 'client.js')

/**
 * Where the five pre-merge source packages live.
 *
 * Resolution order:
 *   1. `DSH_COMPOSER_SOURCES` — explicit override.
 *   2. `../sources` beside this package — the layout inside the dsh-plugins repo,
 *      which keeps the repo self-contained.
 *   3. `<DSH_PROFILE_DIR>/.vendor` — a profile that vendors its plugins.
 *   4. `$DSH_PLUGINS_DIR` (default `~/.dsh/plugins`) — a machine that installs
 *      the merged-away packages once for every profile.
 */
const sourcesRoot = (() => {
  const override = process.env.DSH_COMPOSER_SOURCES
  if (override) return resolve(override)
  const repoSources = resolve(pkgRoot, '..', 'sources')
  if (existsSync(repoSources)) return repoSources
  const profile = process.env.DSH_PROFILE_DIR ?? join(homedir(), '.dsh', 'profiles', 'desktop')
  const vendor = join(profile, '.vendor')
  if (existsSync(vendor)) return vendor
  return process.env.DSH_PLUGINS_DIR ?? join(homedir(), '.dsh', 'plugins')
})()

/**
 * Piece order is deliberate: the left/right composer buttons first (so a
 * reader of the merged file meets them in the order they appear on screen),
 * then the dock stylesheet, then the meter that lives in that dock.
 *
 * @type {{ id: string, file: string, why: string }[]}
 */
const PIECES = [
  {
    id: 'dsh-client-ui-new-session',
    file: join(sourcesRoot, 'dsh-client-ui-new-session/lib/client.js'),
    why: 'conversation.input.left, order -100',
  },
  {
    id: 'dsh-client-ui-compact-button',
    file: join(sourcesRoot, 'dsh-client-ui-compact-button/lib/client.js'),
    why: 'conversation.input.right, order 0',
  },
  {
    id: 'dsh-client-ui-brief-send',
    file: join(sourcesRoot, 'dsh-client-ui-brief-send/lib/client.js'),
    why: 'conversation.input.right, order 1',
  },
  {
    id: 'dsh-client-ui-composer-dock-wrap',
    file: join(sourcesRoot, 'dsh-client-ui-composer-dock-wrap/lib/client.js'),
    why: 'layout-only stylesheet for the composer dock row',
  },
  {
    id: 'dsh-call-meter',
    file: join(sourcesRoot, 'dsh-call-meter/client/client.js'),
    why: 'conversation.composer.dock, order 3',
  },
]

/** Union of the five pieces' client service dependencies. */
const INJECT = ['slots', 'locale', 'sessions', 'uiWorkspace']

/**
 * Cut the body out of one `window.__ModuleLoader__.load({ factory })` file.
 *
 * @param {string} text - whole source file.
 * @param {string} id - package name, for error messages.
 * @returns {string} the factory body, without the loader wrapper.
 */
function factoryBody(text, id) {
  const lines = text.split('\n')
  while (lines.length > 0 && lines[lines.length - 1].trim() === '') lines.pop()

  /* Trailing loader close: `});` or `})`. */
  const close = lines[lines.length - 1]?.trim()
  if (close !== '});' && close !== '})') {
    throw new Error(`${id}: loader call is not closed (tail ${JSON.stringify(close)})`)
  }
  lines.pop()

  /* Then the factory's own closing brace: `}` or `},`. */
  const brace = lines[lines.length - 1]?.trim()
  if (brace !== '}' && brace !== '},') {
    throw new Error(`${id}: unexpected factory tail ${JSON.stringify(brace)}`)
  }
  lines.pop()

  const open = lines.findIndex((line) => /\bfactory\b/.test(line))
  if (open < 0) throw new Error(`${id}: no factory in client artifact`)

  return lines.slice(open + 1).join('\n')
}

const parts = [
  '/**',
  ' * dsh-composer-kit — browser half.',
  ' *',
  ' * Generated by scripts/build-client.mjs from five separate plugins. Each piece',
  ' * below is the verbatim factory body of the package named in its banner, wrapped',
  ' * in its own IIFE so the `module`/`exports` shim and every local name stay',
  ' * private. One module id (the package name) applies all five, which is what the',
  ' * client roster requires: it applies only the module whose id matches the bundle.',
  ' *',
  ' * Do not hand-edit the piece bodies; edit the source packages and re-run the',
  ' * build script.',
  ' */',
  'window.__ModuleLoader__.load({',
  "  id: 'dsh-composer-kit',",
  '  factory: (require) => {',
  '    const pieces = []',
  '',
]

for (const piece of PIECES) {
  if (!existsSync(piece.file)) throw new Error(`missing source: ${piece.file}`)
  const body = factoryBody(readFileSync(piece.file, 'utf8'), piece.id)
  parts.push(`    // ===== ${piece.id} — ${piece.why} =====`)
  parts.push('    pieces.push((function (require) {')
  parts.push(body)
  parts.push('    })(require))')
  parts.push('')
}

parts.push(`    const inject = ${JSON.stringify(INJECT)}`)
parts.push('    return {')
parts.push('      inject,')
parts.push('      apply(ctx) {')
parts.push('        for (const piece of pieces) {')
parts.push("          if (typeof piece.apply === 'function') piece.apply(ctx)")
parts.push('        }')
parts.push('      },')
parts.push('    }')
parts.push('  },')
parts.push('})')
parts.push('')

const output = parts.join('\n')
const check = process.argv.includes('--check')

if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : null
  if (current !== output) {
    console.error('client/client.js is out of date; re-run without --check')
    process.exit(1)
  }
  console.log('client/client.js is up to date')
} else {
  writeFileSync(target, output)
  console.log(`wrote ${target} (${output.length} bytes, ${output.split('\n').length} lines)`)
}
